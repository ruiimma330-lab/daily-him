#!/usr/bin/env bash
set -Eeuo pipefail

umask 077

APP_DIR="${APP_DIR:-/opt/dailyhim}"
ENV_FILE="${ENV_FILE:-/etc/dailyhim.env}"
REPO_URL="${REPO_URL:-}"
BRANCH="${BRANCH:-main}"
APP_NAME="${APP_NAME:-dailyhim}"
APP_PORT="${APP_PORT:-3000}"
APP_USER="${APP_USER:-dailyhim}"
APP_HOME="${APP_HOME:-/var/lib/dailyhim}"
NODE_MAJOR=22
ENV_TMP=""

cleanup() {
  if [[ -n "$ENV_TMP" ]]; then
    rm -f "$ENV_TMP"
  fi
}
trap cleanup EXIT

if [[ "${EUID}" -ne 0 ]]; then
  echo "请使用 root 运行：sudo bash setup.sh" >&2
  exit 1
fi

log() {
  printf '\n==> %s\n' "$1"
}

run_as_app() {
  runuser --preserve-environment -u "$APP_USER" -- env HOME="$APP_HOME" PATH="$PATH" "$@"
}

wait_for_health() {
  local url="$1" attempts="${2:-30}"
  for ((i = 1; i <= attempts; i += 1)); do
    if curl -fsS "$url"; then
      printf '\n'
      return 0
    fi
    sleep 2
  done
  echo "健康检查超时：$url" >&2
  return 1
}

append_env() {
  local file="$1" name="$2" value="$3"
  printf '%s=%q\n' "$name" "$value" >>"$file"
}

read_hidden() {
  local prompt="$1" default="${2:-}" required="${3:-0}" value
  while true; do
    printf '%s' "$prompt" >/dev/tty
    IFS= read -r -s value </dev/tty
    printf '\n' >/dev/tty
    if [[ -z "$value" ]]; then
      value="$default"
    fi
    if [[ "$required" != "1" || -n "$value" ]]; then
      REPLY="$value"
      return
    fi
    printf '此项不能为空，请重新输入。\n' >/dev/tty
  done
}

create_env_file() {
  if [[ -e "$ENV_FILE" ]]; then
    chmod 600 "$ENV_FILE"
    return
  fi
  if [[ ! -r /dev/tty ]]; then
    echo "首次配置需要交互式终端（/dev/tty）。" >&2
    exit 1
  fi

  log "首次创建 $ENV_FILE（输入内容不会回显）"
  ENV_TMP="$(mktemp)"
  {
    echo "# Daily Him production environment"
    echo "# Generated by deploy/hk/setup.sh; keep mode 600."
  } >"$ENV_TMP"

  append_env "$ENV_TMP" NODE_ENV production
  append_env "$ENV_TMP" PORT "$APP_PORT"
  append_env "$ENV_TMP" STORE_DATA_DIR "$APP_HOME"

  read_hidden "站点网址 PUBLIC_SITE_URL [https://dailyhim.cn]：" "https://dailyhim.cn" 1
  append_env "$ENV_TMP" PUBLIC_SITE_URL "$REPLY"

  read_hidden "DeepSeek 密钥 DEEPSEEK_CHAT_API_KEY：" "" 1
  append_env "$ENV_TMP" DEEPSEEK_CHAT_API_KEY "$REPLY"

  read_hidden "ElevenLabs 密钥 ELEVENLABS_API_KEY：" "" 1
  append_env "$ENV_TMP" ELEVENLABS_API_KEY "$REPLY"

  read_hidden "Turso 地址 TURSO_DATABASE_URL：" "" 1
  append_env "$ENV_TMP" TURSO_DATABASE_URL "$REPLY"

  read_hidden "Turso Token TURSO_AUTH_TOKEN：" "" 1
  append_env "$ENV_TMP" TURSO_AUTH_TOKEN "$REPLY"

  read_hidden "可选站点总闸 APP_PASSWORD（直接回车为关闭）：" "" 0
  append_env "$ENV_TMP" APP_PASSWORD "$REPLY"

  read_hidden "模型 LLM_MODEL [deepseek-flash]：" "deepseek-flash" 1
  append_env "$ENV_TMP" LLM_MODEL "$REPLY"

  read_hidden "模型超时毫秒 LLM_TIMEOUT_MS [90000]：" "90000" 1
  append_env "$ENV_TMP" LLM_TIMEOUT_MS "$REPLY"

  read_hidden "推理强度 LLM_EFFORT [low]：" "low" 1
  append_env "$ENV_TMP" LLM_EFFORT "$REPLY"

  read_hidden "可选全局语音 ID VOICE_ID（直接回车使用角色锁定值）：" "" 0
  append_env "$ENV_TMP" VOICE_ID "$REPLY"

  read_hidden "可选 TTS 模型 TTS_MODEL（直接回车使用角色锁定值）：" "" 0
  append_env "$ENV_TMP" TTS_MODEL "$REPLY"

  read_hidden "可选管理员账号 ADMINS（多个用逗号分隔）：" "" 0
  append_env "$ENV_TMP" ADMINS "$REPLY"

  read_hidden "可选朋友圈管理员 MOMENTS_ADMINS（多个用逗号分隔）：" "" 0
  append_env "$ENV_TMP" MOMENTS_ADMINS "$REPLY"

  read_hidden "朋友圈回复同步 MOMENTS_SYNC [0]：" "0" 1
  append_env "$ENV_TMP" MOMENTS_SYNC "$REPLY"

  append_env "$ENV_TMP" SESSION_SECRET "$(openssl rand -hex 32)"
  append_env "$ENV_TMP" MOMENTS_REFRESH_SECRET "$(openssl rand -hex 32)"
  append_env "$ENV_TMP" MOVED_TO_URL ""

  install -o root -g root -m 600 "$ENV_TMP" "$ENV_FILE"
  rm -f "$ENV_TMP"
  ENV_TMP=""
}

log "安装系统依赖"
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y --no-install-recommends ca-certificates curl git gnupg nginx certbot python3-certbot-nginx openssl

current_node_major=0
if command -v node >/dev/null 2>&1; then
  current_node_major="$(node -p "Number(process.versions.node.split('.')[0])" 2>/dev/null || echo 0)"
fi
if [[ "$current_node_major" -ne "$NODE_MAJOR" ]]; then
  log "安装 Node.js ${NODE_MAJOR} LTS"
  curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash -
  apt-get install -y nodejs
fi

log "安装 PM2"
npm install --global pm2@latest --no-audit --no-fund

if ! id "$APP_USER" >/dev/null 2>&1; then
  useradd --system --home-dir "$APP_HOME" --create-home --shell /usr/sbin/nologin "$APP_USER"
fi
install -d -o "$APP_USER" -g "$APP_USER" -m 700 "$APP_HOME"

log "同步代码到 $APP_DIR"
if [[ -z "$REPO_URL" ]]; then
  if [[ -d "$APP_DIR/.git" ]]; then
    REPO_URL="$(git -C "$APP_DIR" remote get-url origin)"
  else
    REPO_URL="https://github.com/ruiimma330-lab/idol-chat.git"
  fi
fi
if [[ -d "$APP_DIR/.git" ]]; then
  git -C "$APP_DIR" remote set-url origin "$REPO_URL"
  git -C "$APP_DIR" fetch origin "$BRANCH"
  git -C "$APP_DIR" checkout "$BRANCH"
  git -C "$APP_DIR" pull --ff-only origin "$BRANCH"
else
  if [[ -e "$APP_DIR" && -n "$(ls -A "$APP_DIR" 2>/dev/null)" ]]; then
    echo "$APP_DIR 已存在且不是 Git 仓库，请先移走该目录。" >&2
    exit 1
  fi
  rm -rf "$APP_DIR"
  git clone --branch "$BRANCH" --single-branch "$REPO_URL" "$APP_DIR"
fi
chown root:root "$APP_DIR"
chmod 755 "$APP_DIR"

log "安装生产依赖"
rm -rf "$APP_DIR/node_modules"
install -d -o "$APP_USER" -g "$APP_USER" -m 755 "$APP_DIR/node_modules"
run_as_app npm --prefix "$APP_DIR" ci --omit=dev --no-audit --no-fund
install -d -o "$APP_USER" -g "$APP_USER" -m 700 "$APP_DIR/cache" "$APP_DIR/cache/audio"

create_env_file
install -d -o "$APP_USER" -g "$APP_USER" -m 700 "$APP_HOME"

log "启动 Daily Him"
set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a
if [[ -S /root/.pm2/rpc.sock ]] && pm2 describe "$APP_NAME" >/dev/null 2>&1; then
  pm2 delete "$APP_NAME" >/dev/null
  pm2 save --force >/dev/null
fi
systemctl disable --now pm2-root >/dev/null 2>&1 || true
if systemctl list-unit-files dailyhim.service >/dev/null 2>&1 || systemctl is-active --quiet dailyhim.service 2>/dev/null; then
  systemctl disable --now dailyhim.service >/dev/null 2>&1 || true
fi
run_as_app pm2 delete "$APP_NAME" >/dev/null 2>&1 || true
# Use -i 1 (portable). Some PM2 builds reject --exec-mode.
run_as_app pm2 start "$APP_DIR/server.js" --name "$APP_NAME" --cwd "$APP_DIR" \
  -i 1 --time
pm2 startup systemd -u "$APP_USER" --hp "$APP_HOME" >/dev/null
run_as_app pm2 save --force >/dev/null
systemctl enable --now "pm2-${APP_USER}"
wait_for_health "http://127.0.0.1:${APP_PORT}/api/health"

log "配置 Nginx"
cat >/etc/nginx/sites-available/dailyhim <<NGINX
server {
    listen 80;
    listen [::]:80;
    server_name www.dailyhim.cn;
    return 301 https://dailyhim.cn\$request_uri;
}

server {
    listen 80;
    listen [::]:80;
    server_name dailyhim.cn;

    client_max_body_size 10m;
    gzip on;
    gzip_vary on;
    gzip_min_length 1024;
    gzip_types text/plain text/css application/json application/javascript application/manifest+json image/svg+xml;

    location ^~ /characters/ {
        proxy_pass http://127.0.0.1:${APP_PORT};
        proxy_http_version 1.1;
        include proxy_params;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }

    location ~* ^/(?:icons|brand)/.*\.(?:avif|gif|jpe?g|png|webp|woff2)$ {
        proxy_pass http://127.0.0.1:${APP_PORT};
        include proxy_params;
        proxy_set_header X-Forwarded-Proto \$scheme;
        expires 7d;
        add_header Cache-Control "public";
    }

    location / {
        proxy_pass http://127.0.0.1:${APP_PORT};
        proxy_http_version 1.1;
        include proxy_params;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 120s;
    }
}
NGINX
ln -sfn /etc/nginx/sites-available/dailyhim /etc/nginx/sites-enabled/dailyhim
rm -f /etc/nginx/sites-enabled/default
nginx -t
systemctl enable --now nginx
systemctl reload nginx

log "申请或复用 HTTPS 证书"
certbot --nginx --non-interactive --agree-tos --register-unsafely-without-email \
  --redirect --keep-until-expiring -d dailyhim.cn -d www.dailyhim.cn
systemctl enable --now certbot.timer

log "部署完成，健康检查"
wait_for_health "https://dailyhim.cn/api/health" 10
